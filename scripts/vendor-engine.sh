#!/bin/sh
# Re-creates third_party/quickjs-engine from upstream liustack/quickjs at the
# pinned release, then applies patches/*.patch on top.
#
#   scripts/vendor-engine.sh
#
# Only the C engine (engine/*.c, engine/*.h), the headers of its small libc
# (engine/libc/**/*.h), its math functions (engine/libc/math.c and
# engine/libc/math/, from musl) and the license files are copied: the generated
# Go assembly, the Go API and the tests of upstream are not, since TinyGo
# cannot use them (see README.md). It also writes quickjs/internal/libm, one
# C file per math source, which TinyGo's cgo builds (TinyGo's wasi-libc has
# no libm).
set -eu

UPSTREAM=https://github.com/liustack/quickjs
TAG=v0.30.2
COMMIT=566d97c97a2fe7db6a3ddd347b742db9b91edeb7

root=$(cd "$(dirname "$0")/.." && pwd)
dst=$root/third_party/quickjs-engine
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

git -c advice.detachedHead=false clone --quiet --depth 1 --branch "$TAG" "$UPSTREAM" "$tmp/quickjs"
got=$(git -C "$tmp/quickjs" rev-parse HEAD)
if [ "$got" != "$COMMIT" ]; then
	echo "vendor-engine.sh: $TAG is $got, expected $COMMIT" >&2
	exit 1
fi

rm -rf "$dst"
mkdir -p "$dst/libc"
src=$tmp/quickjs/engine
cp "$src"/*.c "$src"/*.h "$src/LICENSE" "$dst/"
(cd "$src/libc" && find . -name '*.h' | while read -r f; do
	mkdir -p "$dst/libc/$(dirname "$f")"
	cp "$f" "$dst/libc/$f"
done)
cp "$src/libc/COPYRIGHT" "$src/libc/README.md" "$dst/libc/"
mkdir -p "$dst/libc/math"
cp "$src/libc/math.c" "$dst/libc/"
cp "$src"/libc/math/*.c "$dst/libc/math/"
for f in LICENSE LICENSE-LIBQUICKJS LICENSE-MIT LICENSE-MODERNC-LIBQUICKJS LICENSE-TLSF NOTICE.md; do
	cp "$tmp/quickjs/$f" "$dst/UPSTREAM-$f"
done

for p in "$root"/patches/*.patch; do
	patch -s -p1 -d "$dst" < "$p"
done

# quickjs/internal/libm: a wrapper per math file, built as engine/test/build.sh
# builds engine/libc (features.h in front of each file)
libm=$root/quickjs/internal/libm
rm -f "$libm"/libc_*.c
for f in "$dst/libc/math.c" "$dst"/libc/math/*.c; do
	rel=${f#"$dst/"}
	name=$(echo "$rel" | sed 's#^libc/##; s#/#_#g')
	cat > "$libm/libc_$name" <<WRAP
/* generated by scripts/vendor-engine.sh: $rel of the vendored engine */
#include "../../../third_party/quickjs-engine/libc/internal/features.h"
#include "../../../third_party/quickjs-engine/$rel"
WRAP
done

cat > "$dst/UPSTREAM" <<EOF
repository: $UPSTREAM
tag:        $TAG
commit:     $COMMIT
path:       engine/ (C sources and headers, libc headers only)
patches:    $(cd "$root" && ls patches/*.patch | tr '\n' ' ')
EOF
echo "vendored $UPSTREAM@$TAG ($COMMIT) into third_party/quickjs-engine"
